#!/usr/bin/env node
// Generates the two static PHP data files used by the visitor-country counter:
//   api/tzcountry.php      IANA time zone name -> ISO 3166-1 alpha-2 country code
//   api/countrynames.php   ISO 3166-1 alpha-2 code -> English country name (for the admin)
// Sources (IANA tz database installed on the build machine, default /usr/share/zoneinfo):
//   zone.tab       one country per zone (wins for zones that zone1970.tab shares between countries)
//   zone1970.tab   fallback for zones missing from zone.tab
//   tzdata.zi or backward   "Link" lines, so legacy names (Asia/Calcutta, US/Eastern) map too
// Etc/*, UTC, GMT and other zones without a country are left out (the counter ignores them), and so
// are the old abbreviation zones (CET, EET, EST, PST8PDT ...), which since tzdata 2024b are links to
// one city's zone and would otherwise count e.g. every "CET" browser as Belgium.
// English names come from Node's ICU (Intl.DisplayNames) and are baked into the file, so the
// server needs no PHP intl extension. Run:  node cpanel-backend/tools/gen-tzcountry.mjs
import { readFileSync, writeFileSync, existsSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ZI = process.env.ZONEINFO || "/usr/share/zoneinfo";
const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../api");
const rows = (f) => readFileSync(path.join(ZI, f), "utf8").split("\n").filter((l) => l && !l.startsWith("#")).map((l) => l.split("\t"));

const map = new Map();
for (const [cc, , zone] of rows("zone.tab")) map.set(zone, cc);
for (const [ccs, , zone] of rows("zone1970.tab")) if (!map.has(zone)) map.set(zone, ccs.split(",")[0]);

// Link lines: "L target alias" (tzdata.zi) or "Link\ttarget\talias" (backward).
const links = [];
for (const f of ["tzdata.zi", "backward"]) {
  const p = path.join(ZI, f);
  if (!existsSync(p)) continue;
  for (const line of readFileSync(p, "utf8").split("\n")) {
    const m = line.match(/^(?:L|Link)\s+(\S+)\s+(\S+)/);
    if (m) links.push([m[1], m[2]]);
  }
}
for (let pass = 0; pass < 4; pass++) { // resolve chains of links
  for (const [target, alias] of links) if (!map.has(alias) && map.has(target)) map.set(alias, map.get(target));
}

const zones = [...map.keys()].filter((z) => !/^(Etc\/|UTC$|GMT|Factory|CET$|MET$|EET$|WET$|EST$|MST$|HST$|EST5EDT$|CST6CDT$|MST7MDT$|PST8PDT$)/.test(z)).sort();
const php = (s) => "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";
const ver = (() => { try { return (readFileSync(path.join(ZI, "tzdata.zi"), "utf8").match(/^# version (\S+)/m) || [])[1] || "unknown"; } catch { return "unknown"; } })();

writeFileSync(path.join(OUT, "tzcountry.php"),
  `<?php\n// GENERATED by cpanel-backend/tools/gen-tzcountry.mjs from IANA tzdata ${ver}. Do not edit by hand.\n` +
  `// IANA time zone name -> ISO 3166-1 alpha-2 country code (${zones.length} zones).\nreturn [\n` +
  zones.map((z) => `  ${php(z)} => ${php(map.get(z))},`).join("\n") + "\n];\n");

const codes = [...new Set(zones.map((z) => map.get(z)))].sort();
const dn = new Intl.DisplayNames(["en"], { type: "region" });
const iso = new Map(rows("iso3166.tab").map(([cc, name]) => [cc, name]));
writeFileSync(path.join(OUT, "countrynames.php"),
  `<?php\n// GENERATED by cpanel-backend/tools/gen-tzcountry.mjs (English names from ICU). Do not edit by hand.\n` +
  `// ISO 3166-1 alpha-2 code -> English country or territory name (${codes.length} entries).\nreturn [\n` +
  codes.map((c) => { let n = ""; try { n = dn.of(c) || ""; } catch {} if (!n || n === c) n = iso.get(c) || c; return `  ${php(c)} => ${php(n)},`; }).join("\n") + "\n];\n");

console.log(`tzcountry.php: ${zones.length} zones; countrynames.php: ${codes.length} countries (tzdata ${ver})`);
